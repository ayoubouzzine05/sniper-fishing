/**
 * Sniper Fishing — normalized internal domain models.
 *
 * These types are independent of any data provider. Provider adapters
 * (lib/providers/*) map raw API responses into these shapes, so the UI and
 * the scoring/safety engines never depend on a specific API.
 */

export type FishingMethod =
  | 'surfcasting'
  | 'shore_spinning'
  | 'harbor'
  | 'rock'
  | 'float'
  | 'boat'
  | 'kayak';

export const FISHING_METHODS: FishingMethod[] = [
  'surfcasting',
  'shore_spinning',
  'harbor',
  'rock',
  'float',
  'boat',
  'kayak'
];

export type LocationType =
  | 'shore'
  | 'harbor'
  | 'port'
  | 'beach'
  | 'rock'
  | 'jetty'
  | 'estuary'
  | 'open_water'
  | 'other';

export type WindUnit = 'kmh' | 'knots' | 'ms';
export type DistanceUnit = 'metric' | 'imperial';
export type TempUnit = 'celsius' | 'fahrenheit';
export type AppLanguage = 'ary' | 'ar' | 'fr' | 'en';
export type ThemeMode = 'light' | 'dark' | 'system';

/** A place the user cares about (searched, picked or saved). */
export interface ForecastLocation {
  id: string;
  name: string;
  latitude: number;
  longitude: number;
  country?: string;
  admin1?: string;
  timezone?: string;
}

/**
 * One hour of marine (wave / ocean) data.
 * All values are in provider-native metric units (m, s, km/h, °C, °).
 * `null` = provider returned no value for this hour (missing, NOT zero).
 * We never invent values for missing data.
 */
export interface MarineHour {
  time: string; // local wall time at the location, 'YYYY-MM-DDTHH:mm'
  waveHeight: number | null;
  waveDirection: number | null;
  wavePeriod: number | null;
  wavePeakPeriod: number | null;
  windWaveHeight: number | null;
  windWaveDirection: number | null;
  windWavePeriod: number | null;
  swellWaveHeight: number | null;
  swellWaveDirection: number | null;
  swellWavePeriod: number | null;
  seaSurfaceTemperature: number | null;
  oceanCurrentVelocity: number | null;
  oceanCurrentDirection: number | null;
  seaLevelHeightMsl: number | null;
}

export interface MarineForecast {
  location: ForecastLocation;
  hours: MarineHour[];
  timezone: string;
  fetchedAt: string; // ISO instant the data was fetched
  source: ProviderMetadata;
}

export interface WeatherHour {
  time: string;
  temperature: number | null;
  apparentTemperature: number | null;
  windSpeed: number | null; // km/h
  windGusts: number | null; // km/h
  windDirection: number | null; // degrees
  precipitation: number | null; // mm/h
  precipitationProbability: number | null; // 0..100
  cloudCover: number | null; // 0..100
  pressureMsl: number | null; // hPa
  humidity: number | null; // 0..100
  visibility: number | null; // km
  weatherCode: number | null; // WMO code
  thunderstorm: number | null; // mm/h of thunderstorm precipitation
}

export interface WeatherDay {
  date: string;
  sunrise: string | null;
  sunset: string | null;
  uvIndexMax: number | null;
}

export interface WeatherForecast {
  location: ForecastLocation;
  hours: WeatherHour[];
  days: WeatherDay[];
  timezone: string;
  fetchedAt: string;
  source: ProviderMetadata;
}

/**
 * Tide predictions. Only populated when a licensed, authoritative tide
 * provider is configured. By default the app has NO tide data and says so.
 */
export interface TidePrediction {
  location: ForecastLocation;
  predictions: { time: string; level: number }[];
  fetchedAt: string;
  source: ProviderMetadata;
  disclaimer: string;
}

/** An official (or app-generated) marine/weather warning. */
export interface MarineWarning {
  id: string;
  area: string;
  message: string;
  issuedAt: string;
  expiresAt?: string;
  severity: 'advisory' | 'watch' | 'warning';
  /** true = from an official service; false = generated by this app */
  official: boolean;
  source: ProviderMetadata;
}

export interface ProviderMetadata {
  provider: string;
  endpoint: string;
  license: string;
  attribution: string;
}

/**
 * A single time slice with marine + atmospheric data merged, as consumed by
 * the scoring and safety engines. `missing` lists factor keys that had no
 * data so the UI can be honest about completeness.
 */
export interface ConditionSnapshot {
  time: string;
  windSpeed: number | null;
  windGusts: number | null;
  windDirection: number | null;
  waveHeight: number | null;
  waveDirection: number | null;
  wavePeriod: number | null;
  swellHeight: number | null;
  swellDirection: number | null;
  swellPeriod: number | null;
  seaSurfaceTemperature: number | null;
  oceanCurrentVelocity: number | null;
  oceanCurrentDirection: number | null;
  seaLevelHeightMsl: number | null;
  temperature: number | null;
  apparentTemperature: number | null;
  precipitation: number | null;
  precipitationProbability: number | null;
  cloudCover: number | null;
  pressureMsl: number | null;
  humidity: number | null;
  visibility: number | null;
  weatherCode: number | null;
  thunderstorm: number | null;
  isDaylight: boolean | null;
  /** 0..1 — share of the key variables that have a value at this hour */
  dataCompleteness: number;
  missing: string[];
}

/** Merged forecast for one location: hourly snapshots + metadata. */
export interface MergedForecast {
  location: ForecastLocation;
  hours: ConditionSnapshot[];
  sunriseByDate: Record<string, { sunrise: string | null; sunset: string | null }>;
  marine: MarineForecast | null;
  weather: WeatherForecast | null;
  marineError: string | null;
  weatherError: string | null;
  fetchedAt: string;
  fromCache: { marine: boolean; weather: boolean };
  sources: { marine: ProviderMetadata | null; weather: ProviderMetadata | null };
}

/* ----------------------------- Scoring ------------------------------ */

export type FactorKey =
  | 'wind'
  | 'gusts'
  | 'wave'
  | 'swell'
  | 'rain'
  | 'visibility'
  | 'daylight'
  | 'seaTemp'
  | 'tide';

/**
 * A configurable scoring profile. All thresholds are in metric units.
 * Profiles are explicit heuristics — not scientifically validated models.
 */
export interface ScoringProfile {
  id: string;
  label: string;
  method: FishingMethod;
  windSpeed: { idealMax: number; poorAbove: number }; // km/h
  gusts: { penalizeAbove: number }; // km/h
  wave: { idealMax: number; poorAbove: number }; // m
  swell: { idealMax: number; poorAbove: number; periodGoodAt: number | null }; // m, m, s
  rain: { lightMax: number; heavyAt: number }; // mm/h
  visibility: { idealMin: number; poorBelow: number }; // km
  daylight: { dawnMinutes: number; duskMinutes: number; nightScore: number };
  seaTemp: { band: [number, number] | null }; // °C, null = not used
  tide: { enabled: boolean };
  weights: Record<FactorKey, number>;
  dataQuality: {
    missingFactorScore: number; // score given to a factor with no data (penalty, not 1)
    staleAfterHours: number;
    staleMultiplier: number;
    minConfidenceFactor: number; // score floor as a fraction of raw score
  };
}

export interface ScoreFactor {
  key: FactorKey;
  /** 0..1 contribution of this factor (before weighting) */
  score01: number;
  weight: number;
  /** the measured value (primary) — null means missing */
  value: number | null;
  /** secondary value (e.g. swell period) — null means missing */
  detail: number | null;
  available: boolean;
  /** i18n key for the explanation, e.g. 'fWindHigh' */
  explanationKey: string;
  explanationParams: Record<string, string | number>;
  /** true when this factor pushed the score up, false when it pushed it down */
  positive: boolean;
}

export interface HourScore {
  time: string;
  score: number; // 0..100
  completeness: number; // 0..1
  factors: ScoreFactor[];
}

export interface BestWindow {
  start: string;
  end: string;
  avgScore: number;
  /** index into HourScore[] of the strongest hour in the window */
  peakIndex: number;
}

/* ------------------------------ Safety ------------------------------ */

export type SafetyStatus =
  | 'favorable'
  | 'caution'
  | 'unfavorable'
  | 'dangerous'
  | 'insufficient_data';

export interface SafetyAlert {
  /** i18n key, e.g. 'aWindDangerous' */
  key: string;
  severity: 'caution' | 'unfavorable' | 'dangerous';
  params: Record<string, string | number>;
  official: boolean;
}

export interface SafetyAssessment {
  status: SafetyStatus;
  alerts: SafetyAlert[];
  /** true when the user should NOT go out (unfavorable or dangerous) */
  doNotGoOut: boolean;
  generatedAt: string;
  /** 0..1 average data completeness across the assessed window */
  completeness: number;
}

export interface SafetyThresholds {
  windCaution: number;
  windUnfavorable: number;
  windDangerous: number; // km/h
  gustDangerous: number; // km/h
  waveCaution: number;
  waveUnfavorable: number; // m
  swellCaution: number; // m
  rainHeavyPerHour: number; // mm/h
  visibilityCaution: number;
  visibilityUnfavorable: number; // km
  nightCaution: boolean;
}

